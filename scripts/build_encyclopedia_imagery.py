#!/usr/bin/env python3
"""Package curated visual-imagery lexicon for file:// browsing; not a scene compiler."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'encyclopedia/imagery.json'
OUT = ROOT / 'encyclopedia/imagery-data.js'

def build(content):
    return ('// Generated by scripts/build_encyclopedia_imagery.py; source: imagery.json\n'
            'window.LORE_IMAGERY = ' + json.dumps(json.loads(content), ensure_ascii=False,
            separators=(',', ':')) + ';\n')

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    expected=build(SRC.read_text(encoding='utf-8'))
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != expected:
            parser.error('imagery-data.js stale; run scripts/build_encyclopedia_imagery.py')
        print('PASS: imagery-data.js matches imagery.json')
    else:
        OUT.write_text(expected,encoding='utf-8')
        print(f'Wrote {OUT}')
if __name__=='__main__':main()
