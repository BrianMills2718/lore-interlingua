"""Generate a file://-compatible browser data bundle from Experiment 014 JSON.

Author only the JSON source files. The script changes no conceptual claims.
Run:
    python scripts/build_experiment_014_study.py
    python scripts/build_experiment_014_study.py --check
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPERIMENT = ROOT / "experiments" / "014-conceptual-representation"
FILES = {
    "model": "concept-model.json",
    "notation": "notation.json",
    "presentations": "presentations.json",
    "storyboards": "storyboard-treatments.json",
}
OUTPUT = EXPERIMENT / "study-data.js"
HEADER = "/* Generated by scripts/build_experiment_014_study.py; do not edit. */\nwindow.LI_EXPERIMENT_014 = "


def compiled_source():
    payload = {key: json.loads((EXPERIMENT / path).read_text(encoding="utf-8"))
               for key, path in FILES.items()}
    # Stable insertion order and compact JSON allow direct file:// use without fetch().
    return HEADER + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the bundle needs regeneration")
    args = parser.parse_args()
    content = compiled_source()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.error("study-data.js is stale; run python scripts/build_experiment_014_study.py")
        print("Experiment 014 offline bundle matches source JSON.")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
